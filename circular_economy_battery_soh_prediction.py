# Standardize column names
df_battery.rename(columns={'Cycle': 'cycle_number', 'Voltage': 'voltage', 'Current': 'current', 'Temperature': 'temperature','SOH': 'soh_percentage'}, inplace=True)

print(f"df_battery: {df_battery.shape}")

#Data Info (Check for missing values and data types)
print(df_battery.info())

# Outlier check for key numerical fields
print("\nBattery Data Descriptive Statistics (check for outliers in max values):")
