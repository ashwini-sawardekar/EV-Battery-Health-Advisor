df_battery.head()

"""### Step 2: Exploratory Data Analysis (EDA)"""

# Remove rows where crucial sensor data is missing
df_battery = df_battery.dropna(subset=['voltage', 'current', 'temperature', 'soh_percentage'])

# Remove outliers using the Interquartile Range (IQR) method
# This is crucial for sensor data to remove spikes caused by measurement errors
def remove_outliers(df, column):
    Q1 = df[column].quantile(0.25)
    Q3 = df[column].quantile(0.75)
    IQR = Q3 - Q1
    return df[(df[column] >= Q1 - 1.5*IQR) & (df[column] <= Q3 + 1.5*IQR)]

for col in ['voltage', 'current', 'temperature']:
    df_battery = remove_outliers(df_battery, col)

"""## Step 2: Select features and target"""

# Normalizing data helps the model converge faster and improves accuracy
scaler = StandardScaler()

features = ['cycle_number', 'voltage', 'current', 'temperature']
X = df_battery[features]
y = df_battery['soh_percentage']

X_scaled = scaler.fit_transform(X)

"""## Step 3: Train model"""

X_train, X_test, y_train, y_test = train_test_split(X_scaled, y, test_size=0.2, random_state=42)

model = RandomForestRegressor(n_estimators=100, max_depth=10, random_state=42)
model.fit(X_train, y_train)

"""## Step 4: Save the model and scalar for the app

"""

# IMPORTANT: Save the scaler to transform future user input exactly like the training data
joblib.dump(model, 'battery_soh_model.pkl')
joblib.dump(scaler, 'scaler.pkl')

print(f"Model Accuracy (R^2): {model.score(X_test, y_test):.4f}")